#!/usr/bin/env python3
"""gen-dispmap.py -- generate dispmap.c: the mshtml dispinterfaces the vendor casts to.

.NET's interop coclass types (HTMLDocument, HTMLTableRow, HTMLTableCell, HTMLBody, ...) are the
dispinterfaces DispHTMLDocument, DispHTMLTableRow, ...: the CLR QueryInterfaces for their IID
and calls IDispatch::Invoke with the DISPIDs fixed in mshtmdid.h, never asking GetIDsOfNames.
The shim's own DISPIDs are dynamic (from GetIDsOfNames), so for each such dispinterface this
emits its IID and its fixed DISPID -> member name table, read from Wine's mshtml.idl. The
element members every DispHTML*Element shares (WINE_HTMLELEMENT_DISPINTERFACE_DECL) are
emitted once. Element-specific DISPIDs collide between element types, so the table is per
dispinterface, never global.

usage: gen-dispmap.py WINE_INCLUDE_DIR > dispmap.c
       (reads mshtml.idl + mshtmdid.h; add a dispinterface to WANT to support another cast)
"""
import os, re, sys

WANT = ["DispHTMLDocument", "DispHTMLBody", "DispHTMLTable", "DispHTMLTableRow",
        "DispHTMLTableCell", "DispHTMLInputElement", "DispHTMLDivElement"]
COMMON = "WINE_HTMLELEMENT_DISPINTERFACE_DECL"

inc = sys.argv[1]
idl = open(os.path.join(inc, "mshtml.idl"), encoding="latin-1").read()
hdr = open(os.path.join(inc, "mshtmdid.h"), encoding="latin-1").read()

defs = {}
for m in re.finditer(r"^#define\s+(DISPID_\w+)\s+([^\n]+?)\s*(?://[^\n]*|/\*[^\n]*)?$", hdr, re.M):
    defs[m.group(1)] = m.group(2)
defs.setdefault("DISPID_VALUE", "0")
memo = {}
def val(expr, depth=0):
    if depth > 60:
        raise ValueError(expr)
    if re.fullmatch(r"DISPID_\w+", expr.strip()):
        name = expr.strip()
        if name not in memo:
            memo[name] = val(defs[name], depth + 1)
        return memo[name]
    e = re.sub(r"\b(DISPID_\w+)\b", lambda m: str(val(m.group(1), depth + 1)), expr)
    e = re.sub(r"(?<=[0-9a-fA-F])[uUlL]+\b", "", e)
    if not re.fullmatch(r"[\s0-9xXa-fA-F()+\-|<>]+", e):
        raise ValueError(expr)
    v = eval(e)
    return v - (1 << 32) if v >= (1 << 31) else v

macros = {}
for m in re.finditer(r"^#define\s+(WINE_\w+_DISPINTERFACE_DECL)[ \t]*((?:[^\n]*\\\n)*[^\n]*)", idl, re.M):
    macros[m.group(1)] = m.group(2).replace("\\\n", "\n")

def expand(text, depth=0):
    if depth > 20:
        raise RecursionError
    return re.sub(r"\b(WINE_\w+_DISPINTERFACE_DECL)\b",
                  lambda m: expand(macros[m.group(1)], depth + 1), text)

MEMBER = re.compile(r"\[([^\]]*?)\bid\(([^)]+)\)[^\]]*\]\s*[\w\s\*]*?\b(\w+)\s*\(")
def members(text):
    out = {}
    for m in MEMBER.finditer(text):
        try:
            out[val(m.group(2))] = m.group(3)
        except (KeyError, ValueError):
            pass
    return out

common = members(expand(COMMON))
dispifaces = {}
for m in re.finditer(r"uuid\(([0-9a-fA-F-]{36})\)\s*\]\s*dispinterface\s+(\w+)\s*\{(.*?)\n\}", idl, re.S):
    dispifaces[m.group(2)] = (m.group(1), m.group(3))

def guid_c(u):
    p = u.split("-")
    b = p[3] + p[4]
    return "{0x%s,0x%s,0x%s,{%s}}" % (p[0], p[1], p[2], ",".join("0x" + b[i:i + 2] for i in range(0, 16, 2)))

out = ["/* dispmap.c -- GENERATED by gen-dispmap.py from Wine's mshtml.idl + mshtmdid.h; do not edit.",
       " * The mshtml dispinterfaces the vendor casts to, with their fixed DISPID -> member tables. */",
       '#include "dispmap.h"', "", "#define N(a) (sizeof(a) / sizeof((a)[0]))", ""]
out.append("static const DispName g_elem_common[] = {")
out += [f'    {{ {i}, "{n}" }},' for i, n in sorted(common.items())]
out.append("};\n")
rows = []
for name in WANT:
    uuid, body = dispifaces[name]
    body = expand(body)
    is_elem = COMMON in dispifaces[name][1] or "WINE_HTMLDATAELEMENT_DISPINTERFACE_DECL" in dispifaces[name][1]
    own = {i: n for i, n in members(body).items() if not (is_elem and common.get(i) == n)}
    out.append(f"static const DispName g_{name}[] = {{")
    out += [f'    {{ {i}, "{n}" }},' for i, n in sorted(own.items())]
    out.append("};\n")
    rows.append(f'    {{ {guid_c(uuid)}, "{name}", {"DISP_ELEM" if is_elem else "DISP_DOC"}, '
                f"g_{name}, N(g_{name}), {1 if is_elem else 0} }},")
    print(f"{name}: {len(own)} own + {len(common) if is_elem else 0} common members", file=sys.stderr)
out.append("static const DispIface g_ifaces[] = {")
out += rows
out.append("};\n")
out.append("""static const char *lookup(const DispName *t, size_t n, DISPID id)
{
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (t[mid].id == id)
            return t[mid].name;
        if (t[mid].id < id)
            lo = mid + 1;
        else
            hi = mid;
    }
    return NULL;
}

const DispIface *dispmap_find(DispKind kind, REFIID riid)
{
    size_t i;
    for (i = 0; i < N(g_ifaces); i++)
        if (g_ifaces[i].kind == kind && IsEqualGUID(&g_ifaces[i].diid, riid))
            return &g_ifaces[i];
    return NULL;
}

const char *dispmap_name(const DispIface *di, DISPID id)
{
    const char *n = lookup(di->names, di->n_names, id);
    if (!n && di->elem_common)
        n = lookup(g_elem_common, N(g_elem_common), id);
    return n;
}""")
print("\n".join(out))
