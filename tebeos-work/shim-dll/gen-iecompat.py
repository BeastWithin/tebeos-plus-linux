#!/usr/bin/env python3
"""gen-iecompat.py -- embed iecompat.js as a C string: writes iecompat.h (run after editing the .js)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "iecompat.js"), encoding="utf-8").read()
lines = src.splitlines(keepends=True)
out = ["/* iecompat.h -- GENERATED by gen-iecompat.py from iecompat.js; do not edit. */\n",
       "static const char IECOMPAT_JS[] =\n"]
out += ["    " + json.dumps(l, ensure_ascii=True) + "\n" for l in lines]
out.append("    ;\n")
open(os.path.join(here, "iecompat.h"), "w").write("".join(out))
